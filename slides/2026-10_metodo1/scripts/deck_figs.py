"""Figures (in Portuguese) and LaTeX table rows for the 2026-10_metodo1 deck.

    python scripts/deck_figs.py          # from the deck folder

Inputs in data/:
  stages_A/, stages_B/   train_lat_then_ecg runs on DTI004 truth5ti_s1
                         (A: net trained on the LAT; B: net fitted to g*),
                         stages.npz + stages_summary.json
  noise_A.json, noise_B.json   train_noise_sweep (same starts A and B)
  knowng_summary.json    train_known_g (target generated by Method 1 itself)
  dti004/                set1 per-truth JSONs (Camps vs Method 1) + SUMMARY.md
Outputs: figures/hoje_*.png, figures/dti004_*.png, sections/tab_*.tex.
Only the optimizer settings kept after the sweep are shown (Adam 1e-4, 5e-4).
"""
import json
import os

import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA, FIG, SEC = (os.path.join(HERE, d) for d in ('data', 'figures', 'sections'))
INK, INK2, SURF, GRID = '#0b0b0b', '#52514e', '#ffffff', '#e6e5e1'
BLUE, ORANGE, GRAY = '#2a78d6', '#eb6834', '#8a8985'
plt.rcParams.update({'figure.facecolor': SURF, 'axes.facecolor': SURF, 'savefig.facecolor': SURF,
                     'text.color': INK, 'axes.labelcolor': INK2, 'xtick.color': INK2,
                     'ytick.color': INK2, 'axes.edgecolor': GRID, 'font.size': 13})
KEEP_LR = (1e-4, 5e-4)
LRTEX = {1e-4: '$10^{-4}$', 5e-4: '$5\\cdot 10^{-4}$'}
fmt_e = lambda x: f'{x:.1e}'.replace('.', ',').replace('e-0', 'e-').replace('e+0', 'e+')
fmt = lambda x, n=2: f'{x:.{n}f}'.replace('.', ',')


def load_stages(tag):
    z = np.load(os.path.join(DATA, f'stages_{tag}', 'stages.npz'))
    sm = json.load(open(os.path.join(DATA, f'stages_{tag}', 'stages_summary.json')))
    names = [str(n) for n in z['names']]
    st = {n: {'tau': z[f'tau_{i}'], 'g': z[f'g_{i}']} for i, n in enumerate(names)}
    rows = {names[0]: sm['g0'], names[1]: sm['init'], names[2]: sm['lat_net']}
    for r in sm['after_ecg']:
        rows[f"after ECG inverse, Adam {r['lr']:g}"] = r
    return z, names, st, rows


zA, nA, sA, rA = load_stages('A')
zB, nB, sB, rB = load_stages('B')
xyz, surf, roots, tau_true = zA['xyz'], zA['surf'], zA['roots'], zA['tau_true']
P = xyz[surf]


def ecg_key(lr):
    return f'after ECG inverse, Adam {lr:g}'


# ---------------------------------------------------------------- maps
def draw(ax, field, cmap, vmin, vmax, view=(0, 2, 1)):
    h, v, d = view
    o = np.argsort(P[:, d])
    sc = ax.scatter(P[o, h], P[o, v], c=field[surf][o], s=3, cmap=cmap, vmin=vmin, vmax=vmax,
                    linewidths=0, rasterized=True)
    ax.scatter(xyz[roots, h], xyz[roots, v], s=20, facecolors='none', edgecolors=INK, linewidths=1.0)
    ax.set_aspect('equal'); ax.set_xticks([]); ax.set_yticks([])
    for s_ in ax.spines.values():
        s_.set_visible(False)
    return sc


def label(r):
    return f"MAE {fmt(r['mae'], 1)} ms · ECG {fmt_e(r['ecg'])}"


def maps_figure(kind, fn):
    cols = [('verdade (FIM)', None, None)]
    for tag, names, st, rows in (('A', nA, sA, rA), ('B', nB, sB, rB)):
        pass
    ncol = 4 if kind == 'lat' else 3
    fig, axs = plt.subplots(2, ncol, figsize=(2.55 * ncol, 5.8))
    for i, (tag, names, st, rows) in enumerate((('A', nA, sA, rA), ('B', nB, sB, rB))):
        start = names[2]
        panels = [('verdade (FIM)', tau_true, None),
                  ('rede no início', st[start]['tau'], rows[start]),
                  ('+ inverso ECG, passo 1e-4', st[ecg_key(1e-4)]['tau'], rows[ecg_key(1e-4)]),
                  ('+ inverso ECG, passo 5e-4', st[ecg_key(5e-4)]['tau'], rows[ecg_key(5e-4)])]
        if kind != 'lat':
            panels = panels[1:]  # the truth has no error
        for j, (ttl, tau, r) in enumerate(panels):
            ax = axs[i, j]
            if kind == 'lat':
                sc = draw(ax, tau, 'Blues', 0, tau_true.max())
            else:
                if r is None:
                    ax.axis('off'); continue
                sc = draw(ax, tau - tau.min() - tau_true, 'RdBu_r', -15, 15)
            ax.set_title(ttl + ('' if r is None else '\n' + label(r)), fontsize=10.5, loc='left')
        axs[i, 0].text(-0.08, 0.5, f'início {tag}', transform=axs[i, 0].transAxes, rotation=90,
                       va='center', ha='right', fontsize=11, fontweight='bold')
    cb = fig.colorbar(sc, ax=axs, orientation='horizontal', fraction=0.035, pad=0.03, aspect=60)
    cb.set_label('tempo de ativação (ms)' if kind == 'lat' else
                 'erro de LAT (ms): vermelho = tarde, azul = cedo')
    fig.savefig(os.path.join(FIG, fn), dpi=170, bbox_inches='tight'); plt.close(fig)


maps_figure('lat', 'hoje_mapas.png')
maps_figure('err', 'hoje_erro.png')

# ---------------------------------------------------------------- table A vs B
def row_tex(label_, a, b, gref=None):
    cell = lambda r: (' & '.join([fmt(r['lat_rms']), fmt(r['mae']), fmt(r['corr'], 4), fmt_e(r['ecg'])])
                      if r is not None else ' & '.join(['--'] * 4))
    return f'    {label_} & {cell(a)} & {cell(b)}\\\\\n'


GSTAR = {'lat_rms': 0.65, 'mae': 0.47, 'corr': 0.9996, 'ecg': 7.6e-3}   # free g fit (fit_g / train_gstar, s1)
with open(os.path.join(SEC, 'tab_hoje.tex'), 'w') as fh:
    fh.write(row_tex('$g_0$ = verdade em $S$', rA[nA[0]], rB[nB[0]]))
    fh.write(row_tex('$g^*$ livre (ajuste ao LAT)', GSTAR, GSTAR))
    fh.write('    \\midrule\n')
    fh.write(row_tex('rede no início', rA[nA[2]], rB[nB[2]]))
    for lr in KEEP_LR:
        fh.write(row_tex(f'+ inverso ECG, passo {LRTEX[lr]}', rA[ecg_key(lr)], rB[ecg_key(lr)]))

# ---------------------------------------------------------------- noise sweep
R = json.load(open(os.path.join(DATA, 'noise_A.json'))) + json.load(open(os.path.join(DATA, 'noise_B.json')))
SIG = sorted({r['sigma'] for r in R})


def med(tag, lr, s, ph, key):
    v = [r[ph][key] for r in R if r['tag'] == tag and r['opt'] == 'adam' and r['lr'] == lr
         and r['sigma'] == s and np.isfinite(r[ph][key])]
    return float(np.median(v)) if v else np.nan


x = np.arange(len(SIG))
xt = [f'{s:g}' for s in SIG]
fig, axs = plt.subplots(1, 3, figsize=(12.5, 4.6))
STY = {(1e-4, 'A'): (ORANGE, '-', 'o'), (5e-4, 'A'): (ORANGE, '--', 's'),
       (1e-4, 'B'): (BLUE, '-', 'o'), (5e-4, 'B'): (BLUE, '--', 's')}
for ax, key, yl, lg in ((axs[0], 'ecg', 'erro do ECG (log)', True), (axs[1], 'mae', 'MAE do LAT (ms, log)', True),
                        (axs[2], 'corr', 'correlação do LAT', False)):
    for tag in ('A', 'B'):
        for lr in KEEP_LR:
            c, ls, mk = STY[(lr, tag)]
            ax.plot(x, [med(tag, lr, s, 'end', key) for s in SIG], ls, color=c, marker=mk, lw=2, ms=6,
                    mec='white', mew=1, label=f'início {tag}, passo {fmt_e(lr)}')
    ax.set_xticks(x); ax.set_xticklabels(xt, fontsize=11)
    ax.set_xlabel('ruído $\\sigma$ nos pesos da rede'); ax.set_ylabel(yl)
    ax.grid(color=GRID, lw=.6)
    for s_ in ('top', 'right'):
        ax.spines[s_].set_visible(False)
    if lg:
        ax.set_yscale('log')
h, l = axs[0].get_legend_handles_labels()
fig.legend(h, l, loc='lower center', ncol=4, frameon=False, bbox_to_anchor=(0.5, -0.04), fontsize=12)
fig.tight_layout(rect=(0, 0.07, 1, 1))
fig.savefig(os.path.join(FIG, 'hoje_ruido.png'), dpi=170); plt.close(fig)

# ---------------------------------------------------------------- known g table
K = json.load(open(os.path.join(DATA, 'knowng_summary.json')))['results']
with open(os.path.join(SEC, 'tab_gconhecido.tex'), 'w') as fh:
    for r in K:
        if r['sigma'] is None:
            lab = f"rede aleatória ({r['tag'].split('_')[1]})"
        elif r['sigma'] == 0:
            lab = '$g_{\\mathrm{v}}$ exato'
        else:
            lab = f"$g_{{\\mathrm{{v}}}} + \\mathcal{{N}}(0,\\,{r['sigma']:g}^2)$".replace('.', '{,}')
        s0, s1 = r['start'], r['end']
        fh.write(f"    {lab} & {('$\\approx 0$' if s0['ecg'] < 1e-10 else fmt_e(s0['ecg']))} & {fmt_e(s1['ecg'])} & {fmt(s1['corr'], 4)} & "
                 f"{fmt(s1['mae'])} & {fmt(s0['g_rms_active'])} & {fmt(s1['g_rms_active'])}\\\\\n")

# ---------------------------------------------------------------- DTI004
TR = [f'truth5ti_s{k}' for k in range(6)]
M = {(t, m): json.load(open(os.path.join(DATA, 'dti004', f'{t}_{m}.json'))) for t in TR for m in ('m1', 'camps')}
with open(os.path.join(SEC, 'tab_dti004.tex'), 'w') as fh:
    for k, t in enumerate(TR):
        for m, lab in (('camps', 'Camps'), ('m1', 'Método 1')):
            s = M[(t, m)]['summary']
            fh.write(f"    {('s' + str(k)) if m == 'camps' else ''} & {lab} & {s['n']} & {s['wall_min']:.0f} & "
                     f"{fmt(s['corr'])} & {fmt(s['lat_mae'], 1)} & {fmt_e(s['ecg'])} & {s['n_roots']:.0f} & "
                     f"{fmt(s['recall'])} & {fmt(s['precision'])} & {100 * s['frac_ge2_1cm']:.0f}\\%\\\\\n")
        if k < 5:
            fh.write('    \\midrule\n')

fig, axs = plt.subplots(1, 3, figsize=(12.5, 4.6), sharey=True)
for ax, key, xl in ((axs[0], 'lat_mae', 'MAE do LAT contra a própria verdade (ms)'),
                    (axs[1], 'recall', 'distância verdade → recuperada (cm)'),
                    (axs[2], 'precision', 'distância recuperada → verdade (cm)')):
    for m, c, lab, a in (('camps', ORANGE, 'Camps (SMC-ABC, 512 partículas)', .25),
                         ('m1', BLUE, 'Método 1 (100 inicializações)', .35)):
        xs = np.concatenate([[r[key] for r in M[(t, m)]['rows']] for t in TR])
        ys = np.concatenate([[r['ecg'] for r in M[(t, m)]['rows']] for t in TR])
        ax.scatter(xs, ys, s=7, color=c, alpha=a, lw=0, label=lab, rasterized=True)
        mx = [M[(t, m)]['summary'][key if key != 'lat_mae' else 'lat_mae'] for t in TR]
        my = [M[(t, m)]['summary']['ecg'] for t in TR]
        ax.scatter(mx, my, s=46, color=c, ec='white', lw=1.2, zorder=3)
    ax.set_yscale('log'); ax.set_xlabel(xl); ax.grid(color=GRID, lw=.6)
    for s_ in ('top', 'right'):
        ax.spines[s_].set_visible(False)
axs[0].set_ylabel('erro do ECG contra a própria verdade (log)')
h, l = axs[0].get_legend_handles_labels()
fig.legend(h, l, loc='lower center', ncol=2, frameon=False, bbox_to_anchor=(0.5, -0.04), markerscale=3, fontsize=12)
fig.tight_layout(rect=(0, 0.07, 1, 1))
fig.savefig(os.path.join(FIG, 'dti004_membros.png'), dpi=170); plt.close(fig)
