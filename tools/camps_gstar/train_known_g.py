"""Known-g test: does the ECG inverse recover a g we know, from near it?

The target is generated by Method 1's own forward from a known ``g_true`` on S
(``g_true`` = FIM truth restricted to S, a realistic g), so ECG error 0 and
the exact map are attainable (no FIM / Method 1 model mismatch). Then, for
each noise level sigma, the network is regressed onto ``g_true + N(0, sigma^2)``
(a frozen residual makes the start exact) and trained on the ECG mismatch only,
exactly as ``train_gstar`` step 4. ``rand`` rows start from a fresh random
network (no regression), the old protocol, as the control.

Environment: RUN_TRUTH, NAME, SIGMAS (ms, comma list), RAND_SEEDS, N_REG,
N_ITER, EPS_SCREEN, BOX, W_CONSIST, RUN_OUT.
"""
import json, os, time
import numpy as np
import torch
from fisiocomPinn import Grid3D
from fisiocomPinn.Trainer import Trainer
from core import camps_mesh
from core.diagnostics import accuracy, admissibility
from core.forward import ECGForward, einthoven_wilson, lead_field, upstroke_for_spacing
from core.loss import ECGMismatch
from core.mesh import surface_faces
from core.metric import Componentwise
from core.operator import DeltaPoisson
from core.output import open_run
from core.screened import ScreenedPoisson
from core.screened_front import ScreenedFront
from core.validate import MapValidator

HERE = os.path.dirname(os.path.abspath(__file__))
RUN_TRUTH = os.path.join(HERE, os.environ.get('RUN_TRUTH', 'outputs/truth5ti_set1'))
NAME = os.environ.get('NAME', 'truth5ti_s1')
SIGMAS = [float(s) for s in os.environ.get('SIGMAS', '0,0.5,1,2,5,10').split(',')]
RAND_SEEDS = [int(s) for s in os.environ.get('RAND_SEEDS', '0,1,2').split(',') if s != '']
N_REG = int(os.environ.get('N_REG', 3000))
N_ITER = int(os.environ.get('N_ITER', 1000))
EPS_SCREEN = float(os.environ.get('EPS_SCREEN', 2.0))
BOX = float(os.environ.get('BOX', 0.01))
WIDTH, LAYERS, N_EIG, NT = 64, 4, 40, 100
LR = float(os.environ.get('LR', 5e-4))
OPT = os.environ.get('OPT', 'adam')            # adam | sgd
ADAM_EPS = float(os.environ.get('ADAM_EPS', 1e-8))
FREEZE_CV = os.environ.get('FREEZE_CV', '0') == '1'
DEVICE = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
SPEED_NAMES = ('fibre', 'cross', 'endo_dense', 'endo_sparse')
RUN = open_run(__file__, f'knowng_{NAME}', header={'NAME': NAME, 'SIGMAS': SIGMAS,
               'RAND_SEEDS': RAND_SEEDS, 'N_REG': N_REG, 'N_ITER': N_ITER})

mesh = camps_mesh.load(os.path.join(RUN_TRUTH, 'mesh.npz'))
A = mesh.A
A4 = np.stack([A[:, 0], A[:, 1] + A[:, 2], A[:, 3], A[:, 4]], axis=1)
sol = np.load(os.path.join(RUN_TRUTH, f'{NAME}.npz'))
sp_ = dict(zip([str(k) for k in sol['speed_keys']], sol['speeds']))
v_true = [float(sp_['fibre']), float(sp_['sheet']), float(sp_['endo_dense']), float(sp_['endo_sparse'])]
keep = [k for k in range(A4.shape[1]) if np.abs(A4[:, k]).max() > 0]
A4 = A4[:, keep]; v_true = [v_true[k] for k in keep]
SPEED_NAMES = tuple(SPEED_NAMES[k] for k in keep)
metric = Componentwise(A4, names=SPEED_NAMES)
D_true = metric.tensor(*v_true)
roots = sol['root_nodes'].astype(np.int64)
tau_fim = np.load(os.path.join(RUN_TRUTH, f'{NAME}_fim.npz'))['tau'].astype(float)
tau_fim -= tau_fim.min()
scale = float(tau_fim.max())
grid = Grid3D(mesh.xyz, mesh.tet)
S = mesh.candidates
endo = np.union1d(mesh.lvendo, mesh.rvendo)
surf = surface_faces(mesh.tet)
f_elem = np.linalg.eigh(A[:, 0])[1][:, :, -1]
ELECS = mesh.electrodes
upstroke, _ = upstroke_for_spacing(grid, v_true[1])
grad_Z = torch.einsum('ab,bed->aed', einthoven_wilson(torch.eye(len(ELECS))), lead_field(grid, ELECS))
t_grid = np.linspace(0.0, scale * 1.05, NT)
ecg = ECGForward(grid, grad_Z, t_grid, upstroke=upstroke, device=str(DEVICE))
op = DeltaPoisson(grid, metric=metric, sparse=str(DEVICE)).to(str(DEVICE))
metric.to(str(DEVICE))
a_s = ScreenedPoisson(grid, f_elem, v_true[0], v_true[1]).surface_weights(endo, surf)[S]
cvb = [(v, v * (1 - BOX), v * (1 + BOX)) for v in v_true]
torch.manual_seed(0)
model = ScreenedFront(grid, f_elem, S, a_s, EPS_SCREEN, g_scale=scale, n_eig=N_EIG, n_layers=LAYERS,
                      width=WIDTH, cv=cvb, learn=True, solver='sparse', screen_D=D_true).to(DEVICE)
s_nodes = model.s_nodes
model.register_buffer('g_off', torch.zeros(len(S), device=DEVICE), persistent=False)
_g_net = model.g
model.g = lambda: _g_net() + model.g_off
init_state = {k: v.clone() for k, v in model.state_dict().items()}

# known g and the synthetic target made by Method 1's own forward
g_true = torch.as_tensor(tau_fim, dtype=torch.float32, device=DEVICE)[s_nodes].clone()
with torch.no_grad():
    p = model.field_from_g(g_true, *model.cv)
    tau_syn = op.potential(p, *model.cv, n_project=0); tau_syn = tau_syn - tau_syn.min()
    V_syn = ecg.from_tau(tau_syn)
gt0 = g_true - g_true.min()
active = gt0 < 5 * EPS_SCREEN
print(f'S={len(S)}; synthetic target max {float(tau_syn.max()):.1f} ms; active candidates (g-gmin<{5 * EPS_SCREEN:g} ms): {int(active.sum())}', flush=True)


def score():
    model.eval()
    with torch.no_grad():
        p = model()
        th = op.potential(p, *model.cv, n_project=0)
        V = ecg.from_tau(th)
        row = accuracy(th, tau_syn)
        g = model.g(); gd = g - g.min()
        row.update(ecg=float(((V - V_syn) ** 2).mean() / (V_syn ** 2).mean()),
                   g_rms_all=float((gd - gt0).pow(2).mean().sqrt()),
                   g_rms_active=float((gd - gt0)[active].pow(2).mean().sqrt()),
                   g_max_active=float((gd - gt0)[active].abs().max()),
                   cv_rel_err=[float(c) / t - 1 for c, t in zip(model.cv, v_true)])
    return row


def run(tag, init):
    model.load_state_dict(init_state, strict=False)
    if init is None:                                  # random network, no regression
        torch.manual_seed(int(tag.split('_')[1]) + 1000)
        for m in model.net.modules():
            if hasattr(m, 'reset_parameters'):
                m.reset_parameters()
        model.g_off.zero_()
    else:
        y = (init / model.g_scale).detach()
        for m in model.net.modules():
            if hasattr(m, 'reset_parameters'):
                m.reset_parameters()
        o = torch.optim.Adam(model.net.parameters(), lr=1e-3)
        for _ in range(N_REG):
            o.zero_grad(set_to_none=True)
            ((model.net(s_nodes).squeeze(-1) - y) ** 2).mean().backward(); o.step()
        with torch.no_grad():
            model.g_off.copy_(init - model.g_scale * model.net(s_nodes).squeeze(-1))
    r0 = score()
    loss = ECGMismatch(grid, op, ecg, V_syn, n_project=0, keep_best=False)
    if FREEZE_CV:
        model.raw.requires_grad_(False)
    params = [q for q in model.parameters() if q.requires_grad]
    opt = (torch.optim.SGD(params, lr=LR) if OPT == 'sgd'
           else torch.optim.Adam(params, lr=LR, eps=ADAM_EPS))
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=N_ITER, eta_min=LR * 0.02)
    val = MapValidator(loss, tau_syn, name=f'map_{tag}', root=RUN, freq=N_ITER, dump_f=1000)
    tr = Trainer(n_epochs=N_ITER, model=model, device=str(DEVICE), adaptive=False, lr=LR,
                 print_steps=N_ITER, patience=None, optimizer=opt, scheduler=sched,
                 ckpt_path=os.path.join(RUN, f'model_{tag}.pt'))
    tr.add_loss(loss, weigth=1); tr.add_validator(val, freq=N_ITER)
    t0 = time.time(); tr.train()
    r1 = score()
    print(f"{tag:8s} start: ECG {r0['ecg']:.2e} corr {r0['corr']:.4f} MAE {r0['mae']:.2f} g_rms(active) {r0['g_rms_active']:.2f} | "
          f"end: ECG {r1['ecg']:.2e} corr {r1['corr']:.4f} MAE {r1['mae']:.2f} g_rms(active) {r1['g_rms_active']:.2f} "
          f"g_max(active) {r1['g_max_active']:.2f} cv_err% {[round(100*e,3) for e in r1['cv_rel_err']]} [{time.time() - t0:.0f}s]", flush=True)
    return {'tag': tag, 'start': r0, 'end': r1}


res = []
gen = torch.Generator(device='cpu').manual_seed(123)
for s in SIGMAS:
    noise = torch.randn(len(S), generator=gen).to(DEVICE) * s
    res.append({'sigma': s, **run(f'sig{s:g}', (g_true + noise).detach())})
for sd in RAND_SEEDS:
    res.append({'sigma': None, **run(f'rand_{sd}', None)})
json.dump({'name': NAME, 'roots': roots.tolist(), 'results': res}, open(os.path.join(RUN, 'summary.json'), 'w'),
          indent=1, default=float)
print('wrote', RUN)
