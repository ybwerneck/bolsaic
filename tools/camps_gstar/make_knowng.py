"""Table and plot of the known-g test (reads results/knowng_summary.json)."""
import json, os
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'results')
R = json.load(open(os.path.join(OUT, 'knowng_summary.json')))['results']
sig = [r for r in R if r['sigma'] is not None]; rnd = [r for r in R if r['sigma'] is None]
BLUE, ORANGE, GRAY, INK, INK2, SURF, GRID = '#2a78d6', '#eb6834', '#8a8985', '#0b0b0b', '#52514e', '#fcfcfb', '#e6e5e1'
plt.rcParams.update({'figure.facecolor': SURF, 'axes.facecolor': SURF, 'savefig.facecolor': SURF, 'axes.edgecolor': GRID,
    'axes.labelcolor': INK2, 'text.color': INK, 'xtick.color': INK2, 'ytick.color': INK2, 'axes.spines.top': False,
    'axes.spines.right': False, 'axes.grid': True, 'grid.color': GRID, 'grid.linewidth': .6, 'font.size': 10})
f = lambda r, k, m: r[k][m]
md = ['# Known-g test (truth5ti_s1; target generated by Method 1 itself)\n',
      'g_true = FIM truth on S. Start = g_true + N(0, sigma^2) (regression + frozen residual), then ECG-only training, 1000 iterations.',
      '"active" = candidates with g_true - min < 10 ms (21 of 601). Errors in ms (g) or relative (ECG).\n',
      '| start | ECG err start | ECG err end | LAT corr end | LAT MAE end (ms) | g rms active start | g rms active end | g max active end |', '|---|---|---|---|---|---|---|---|']
for r in sig + rnd:
    lab = f"g_true + N(0, {r['sigma']:g}^2)" if r['sigma'] is not None else f"random network ({r['tag']})"
    md.append(f"| {lab} | {f(r,'start','ecg'):.2e} | {f(r,'end','ecg'):.2e} | {f(r,'end','corr'):.4f} | {f(r,'end','mae'):.2f} | "
              f"{f(r,'start','g_rms_active'):.2f} | {f(r,'end','g_rms_active'):.2f} | {f(r,'end','g_max_active'):.2f} |")
open(os.path.join(OUT, 'knowng_table.md'), 'w').write('\n'.join(md) + '\n')
x = np.arange(len(sig)); xl = [f"{r['sigma']:g}" for r in sig]
fig, (a, b) = plt.subplots(1, 2, figsize=(11, 4.4))
for ax, key, yl, lg in ((a, 'ecg', 'relative ECG error (log)', True), (b, 'g_rms_active', 'rms error of g on active candidates (ms)', False)):
    ax.plot(x, [f(r, 'start', key) for r in sig], 'o-', color=BLUE, lw=2, ms=7, mec=SURF, mew=1.3, label='start (g_true + noise)')
    ax.plot(x, [f(r, 'end', key) for r in sig], 'o-', color=ORANGE, lw=2, ms=7, mec=SURF, mew=1.3, label='after ECG inverse')
    lo, hi = min(f(r, 'end', key) for r in rnd), max(f(r, 'end', key) for r in rnd)
    ax.axhspan(lo, hi, color=GRAY, alpha=.25, lw=0, label='random-network control, after (3 seeds)')
    ax.set_xticks(x); ax.set_xticklabels(xl); ax.set_xlabel('noise sigma on g (ms)'); ax.set_ylabel(yl)
    if lg: ax.set_yscale('log')
    ax.legend(frameon=False, fontsize=9, loc='upper left', bbox_to_anchor=(0, -0.2), ncol=1)
a.set_title('ECG error recovers...', loc='left', fontsize=12); b.set_title('...but g is not recovered for sigma >= 5 ms', loc='left', fontsize=12)
fig.tight_layout(); fig.savefig(os.path.join(OUT, 'fig5_known_g.png'), dpi=160)
print(open(os.path.join(OUT, 'knowng_table.md')).read())
